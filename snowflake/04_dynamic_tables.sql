-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT sub.ID AS ENTITY_ID, sub.NAME AS ENTITY_NAME,
       sub.REGION, sub.CATEGORY, sub.STATUS,
       COUNT(*) AS EVENT_COUNT, SUM(observation.GRID_EVENT_COUNT) AS GRID_EVENT_COUNT,
       SUM(observation.OPERATING_HOURS) AS OPERATING_HOURS,
       SUM(observation.PLANNED_HOURS) AS PLANNED_HOURS,
       SUM(observation.DOWNTIME_HOURS) AS DOWNTIME_HOURS,
       SUM(observation.PM_DUE) AS PM_DUE, SUM(observation.PM_COMPLETED) AS PM_COMPLETED,
       SUM(observation.PROTECTION_CHECKS) AS PROTECTION_CHECKS,
       SUM(observation.IN_LIMIT_SAMPLES) AS IN_LIMIT_SAMPLES, SUM(observation.SCADA_SAMPLES) AS SCADA_SAMPLES,
       SUM(observation.PROTECTION_ALARMS) AS PROTECTION_ALARMS,
       100.0 * SUM(observation.IN_LIMIT_SAMPLES) / NULLIF(SUM(observation.SCADA_SAMPLES), 0) AS IN_LIMIT_PCT,
       1000.0 * SUM(observation.PROTECTION_ALARMS) / NULLIF(SUM(observation.PROTECTION_CHECKS), 0) AS ALARMS_PER_1K,
       100.0 * SUM(observation.OPERATING_HOURS) / NULLIF(SUM(observation.PLANNED_HOURS), 0) AS CONNECTION_AVAILABILITY_PCT,
       100.0 * SUM(observation.PM_COMPLETED) / NULLIF(SUM(observation.PM_DUE), 0) AS PM_COMPLIANCE_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.SUBSTATION_DAILY observation
JOIN RAW.SUBSTATIONS sub ON sub.ID = observation.ENTITY_ID
GROUP BY sub.ID, sub.NAME, sub.REGION, sub.CATEGORY, sub.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(IN_LIMIT_SAMPLES) AS IN_LIMIT_SAMPLES, SUM(SCADA_SAMPLES) AS SCADA_SAMPLES,
       SUM(PROTECTION_CHECKS) AS PROTECTION_CHECKS, SUM(PROTECTION_ALARMS) AS PROTECTION_ALARMS,
       SUM(GRID_EVENT_COUNT) AS GRID_EVENT_COUNT,
       100.0 * SUM(IN_LIMIT_SAMPLES) / NULLIF(SUM(SCADA_SAMPLES), 0) AS IN_LIMIT_PCT
FROM RAW.SUBSTATION_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.GRID_EVENT_CAUSES
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT ROOT_CAUSE, SUM(GRID_EVENT_COUNT) AS GRID_EVENT_COUNT,
       SUM(DOWNTIME_HOURS) AS DOWNTIME_HOURS,
       SUM(SCADA_SAMPLES) - SUM(IN_LIMIT_SAMPLES) AS OUT_OF_LIMIT_SAMPLES
FROM RAW.SUBSTATION_DAILY
WHERE GRID_EVENT_COUNT > 0
GROUP BY ROOT_CAUSE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(IN_LIMIT_SAMPLES) AS IN_LIMIT_SAMPLES, SUM(SCADA_SAMPLES) AS SCADA_SAMPLES,
         SUM(PROTECTION_CHECKS) AS PROTECTION_CHECKS, SUM(PROTECTION_ALARMS) AS FAILED,
         SUM(GRID_EVENT_COUNT) AS GRID_EVENTS,
         SUM(OPERATING_HOURS) AS OPERATING_HOURS, SUM(PLANNED_HOURS) AS PLANNED_HOURS,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.SUBSTATION_DAILY
), network AS (SELECT COUNT(*) AS SUBSTATION_COUNT FROM RAW.SUBSTATIONS),
readiness AS (
  SELECT 100.0 * SUM(LEAST(ON_HAND_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT
  FROM RAW.EQUIPMENT_READINESS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'In-Limit SCADA Samples' AS TITLE,
         100.0 * IN_LIMIT_SAMPLES / NULLIF(SCADA_SAMPLES, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Grid Events', GRID_EVENTS, '' FROM observations
  UNION ALL SELECT 3, 'Protection Alarms per 1k Checks', 1000.0 * FAILED / NULLIF(PROTECTION_CHECKS, 0), '' FROM observations
  UNION ALL SELECT 4, 'SCADA Samples', SCADA_SAMPLES, '' FROM observations
  UNION ALL SELECT 5, 'Connection Availability', 100.0 * OPERATING_HOURS / NULLIF(PLANNED_HOURS, 0), '%' FROM observations
  UNION ALL SELECT 6, 'Grid Connection Substations', SUBSTATION_COUNT, '' FROM network
  UNION ALL SELECT 7, 'Protection Spares Readiness', COVERAGE_PCT, '%' FROM readiness
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.TITLE = 'Protection Alarms per 1k Checks' THEN TRIM(TO_VARCHAR(metrics.VALUE_NUM, '990.00'))
                WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.GRID_EVENT_CAUSES SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
