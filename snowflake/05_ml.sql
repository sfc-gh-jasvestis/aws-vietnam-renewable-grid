-- Grid event-risk scoring and SCADA sample volume forecast over the synthetic snapshot.
-- Predicts P(grid event in the next 7 days) per substation and reports
-- out-of-time holdout metrics; nothing is seeded as a prediction.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.GRID_EVENT_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, t.CATEGORY, t.AGE_YEARS,
       r.VOLTAGE_DEV_PCT, r.TRANSFORMER_LOAD_PCT,
       AVG(r.VOLTAGE_DEV_PCT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS VOLTAGE_DEV_7D,
       SUM(r.GRID_EVENT_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS GRID_EVENTS_30D,
       IFF(SUM(r.GRID_EVENT_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'GRID_EVENT', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.SUBSTATION_DAILY r JOIN RAW.SUBSTATIONS t ON t.ID = r.ENTITY_ID
-- Regional events (transmission line outage, tropical storm) are not substation-driven, so they are excluded from training.
WHERE r.ROOT_CAUSE NOT IN ('Transmission line outage', 'Tropical storm') OR r.GRID_EVENT_COUNT = 0;

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.GRID_EVENT_TRAIN AS
SELECT CATEGORY, AGE_YEARS, VOLTAGE_DEV_PCT, TRANSFORMER_LOAD_PCT, VOLTAGE_DEV_7D, GRID_EVENTS_30D, LABEL
FROM ML.GRID_EVENT_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.GRID_EVENT_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, AGE_YEARS, VOLTAGE_DEV_PCT, TRANSFORMER_LOAD_PCT, VOLTAGE_DEV_7D, GRID_EVENTS_30D, LABEL
FROM ML.GRID_EVENT_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.GRID_EVENT_RISK_MODEL(
  INPUT_DATA => TABLE(ML.GRID_EVENT_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.GRID_EVENT_RISK_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.GRID_EVENT_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'AGE_YEARS', AGE_YEARS, 'VOLTAGE_DEV_PCT', VOLTAGE_DEV_PCT,
           'TRANSFORMER_LOAD_PCT', TRANSFORMER_LOAD_PCT, 'VOLTAGE_DEV_7D', VOLTAGE_DEV_7D, 'GRID_EVENTS_30D', GRID_EVENTS_30D)):probability:GRID_EVENT::FLOAT AS P
  FROM ML.GRID_EVENT_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'GRID_EVENT', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'GRID_EVENT', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'GRID_EVENT', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'GRID_EVENT', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per substation (label unknown, so excluded from features).
CREATE TABLE ML.GRID_EVENT_RISK_SCORES AS
WITH latest AS (
  SELECT * FROM ML.GRID_EVENT_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.GRID_EVENT_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'AGE_YEARS', AGE_YEARS, 'VOLTAGE_DEV_PCT', VOLTAGE_DEV_PCT,
           'TRANSFORMER_LOAD_PCT', TRANSFORMER_LOAD_PCT, 'VOLTAGE_DEV_7D', VOLTAGE_DEV_7D, 'GRID_EVENTS_30D', GRID_EVENTS_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:GRID_EVENT::FLOAT, 4) AS GRID_EVENT_PROB_7D,
       CASE WHEN P:probability:GRID_EVENT::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:GRID_EVENT::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Network-wide SCADA sample volume forecast (14 days) from the daily series.
CREATE VIEW ML.DAILY_VOLUME AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, SUM(SCADA_SAMPLES)::FLOAT AS SCADA_SAMPLES
FROM RAW.SUBSTATION_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.VOLUME_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_VOLUME),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'SCADA_SAMPLES'
);

CREATE TABLE ML.VOLUME_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, ROUND(FORECAST) AS SCADA_SAMPLES,
       ROUND(GREATEST(0, LOWER_BOUND)) AS LOWER_BOUND, ROUND(UPPER_BOUND) AS UPPER_BOUND
FROM TABLE(ML.VOLUME_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
